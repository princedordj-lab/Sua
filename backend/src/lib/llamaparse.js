/**
 * LlamaParse (LlamaCloud v2 REST) client.
 *
 * Pure I/O: no database and no extraction state. lib/extraction.js owns the
 * resumable state machine and persistence; this module only turns the three
 * REST stages into small, validated return values.
 *
 * Logs never contain the API key, document text or signed URLs. Error messages
 * carry an HTTP status and a short provider detail capped below.
 */

import { llamaParse } from "../config/ai-pipeline.js";

const BASE_URL = "https://api.cloud.llamaindex.ai";
const PARSE_STATUSES = new Set(["PENDING", "RUNNING", "COMPLETED", "FAILED", "CANCELLED"]);

const MIME_TYPES = {
  pdf: "application/pdf",
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  pptx: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
};

export class LlamaParseError extends Error {
  constructor(code, message, { status = null, retryable = false } = {}) {
    super(message);
    this.name = "LlamaParseError";
    this.code = code;
    this.status = status;
    this.retryable = retryable;
  }
}

export function llamaParseEnabled() {
  return llamaParse.enabled;
}

export function llamaParseEligible(format) {
  if (!llamaParse.enabled) return false;
  return llamaParse.formats.includes(String(format ?? "").toLowerCase());
}

export function llamaparseMimeType(format) {
  return MIME_TYPES[String(format ?? "").toLowerCase()] ?? "application/octet-stream";
}

export function isRetryable(error) {
  return Boolean(error?.retryable);
}

function apiKey() {
  const key = process.env.LLAMA_CLOUD_API_KEY;
  if (!key) {
    throw new LlamaParseError("LLAMA_AUTH", "LLAMA_CLOUD_API_KEY is not configured");
  }
  return key;
}

function codeForStatus(status) {
  if (status === 401 || status === 403) return ["LLAMA_AUTH", false];
  if (status === 402) return ["LLAMA_QUOTA", false];
  if (status === 413) return ["LLAMA_TOO_LARGE", false];
  if (status === 408 || status === 429 || status >= 500) return ["LLAMA_TRANSIENT", true];
  return ["LLAMA_BAD_REQUEST", false];
}

function parseStatus(source) {
  const status = String(source?.status ?? "").toUpperCase();
  if (!PARSE_STATUSES.has(status)) {
    throw new LlamaParseError("LLAMA_INVALID_RESPONSE", "parse response has no known status");
  }
  return status;
}

function creditsOf(job) {
  const credits = job?.usage?.credits;
  return Number.isFinite(credits) ? credits : null;
}

function shortDetail(text) {
  return String(text ?? "")
    .replace(/\s+/g, " ")
    .slice(0, 200)
    .trim();
}

async function requestJson(
  path,
  {
    method = "GET",
    headers = {},
    body,
    timeoutMs = llamaParse.requestTimeoutMs,
    fetchImpl = fetch,
  } = {},
) {
  let response;
  try {
    response = await fetchImpl(`${BASE_URL}${path}`, {
      method,
      headers: {
        Authorization: `Bearer ${apiKey()}`,
        Accept: "application/json",
        ...headers,
      },
      body,
      signal: AbortSignal.timeout(timeoutMs),
    });
  } catch (error) {
    if (error?.name === "TimeoutError" || error?.name === "AbortError") {
      throw new LlamaParseError("LLAMA_TIMEOUT", `request timed out after ${timeoutMs}ms`, {
        retryable: true,
      });
    }
    throw new LlamaParseError("LLAMA_TRANSIENT", error?.message ?? "network error", {
      retryable: true,
    });
  }

  const text = await response.text().catch(() => "");
  if (!response.ok) {
    const [code, retryable] = codeForStatus(response.status);
    const detail = shortDetail(text) || response.statusText;
    throw new LlamaParseError(code, `${response.status} ${detail}`.trim(), {
      status: response.status,
      retryable,
    });
  }

  try {
    return text ? JSON.parse(text) : {};
  } catch {
    throw new LlamaParseError("LLAMA_INVALID_RESPONSE", "provider returned non-JSON", {
      status: response.status,
    });
  }
}

/** Stage A: POST /api/v1/beta/files — the boundary is generated by fetch. */
export async function uploadToLlamaCloud({
  bytes,
  filename = "document",
  mimeType = "application/octet-stream",
  timeoutMs = llamaParse.uploadTimeoutMs,
  fetchImpl = fetch,
}) {
  if (!bytes?.length) {
    throw new LlamaParseError("LLAMA_BAD_REQUEST", "empty document");
  }
  const form = new FormData();
  form.append("purpose", "parse");
  form.append("file", new Blob([bytes], { type: mimeType }), filename);

  const data = await requestJson("/api/v1/beta/files", {
    method: "POST",
    body: form,
    timeoutMs,
    fetchImpl,
  });
  const fileId = typeof data?.id === "string" ? data.id : null;
  if (!fileId) {
    throw new LlamaParseError("LLAMA_INVALID_RESPONSE", "upload response is missing id");
  }
  return { fileId };
}

/** Stage B: POST /api/v2/parse — status/id are top-level on this response. */
export async function createParseJob({
  fileId,
  tier = llamaParse.tier,
  version = llamaParse.version,
  languages = llamaParse.languages,
  maxPages = null,
  timeoutMs = llamaParse.requestTimeoutMs,
  fetchImpl = fetch,
}) {
  if (!fileId) {
    throw new LlamaParseError("LLAMA_BAD_REQUEST", "missing file id");
  }
  const payload = {
    file_id: fileId,
    tier,
    version,
    output_options: {
      markdown: { tables: { output_tables_as_markdown: true } },
    },
    processing_options: {
      ocr_parameters: { languages: languages?.length ? languages : ["en"] },
    },
  };
  if (Number.isFinite(maxPages) && maxPages > 0) {
    payload.page_ranges = { max_pages: Math.round(maxPages) };
  }

  const data = await requestJson("/api/v2/parse", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload),
    timeoutMs,
    fetchImpl,
  });
  const jobId = typeof data?.id === "string" ? data.id : null;
  if (!jobId) {
    throw new LlamaParseError("LLAMA_INVALID_RESPONSE", "parse response is missing id");
  }
  return { jobId, status: parseStatus(data) };
}

/** Stage C part 1: GET /api/v2/parse/{job_id} — status lives under job. */
export async function getParseJob({
  jobId,
  timeoutMs = llamaParse.requestTimeoutMs,
  fetchImpl = fetch,
}) {
  if (!jobId) {
    throw new LlamaParseError("LLAMA_BAD_REQUEST", "missing job id");
  }
  const data = await requestJson(`/api/v2/parse/${encodeURIComponent(jobId)}`, {
    timeoutMs,
    fetchImpl,
  });
  const job = data?.job ?? data;
  return {
    jobId,
    status: parseStatus(job),
    errorMessage: job?.error_message ?? null,
    credits: creditsOf(job),
  };
}

/** Stage C part 2: completed pages plus billed credits, in one request. */
export async function getParseResult({
  jobId,
  timeoutMs = llamaParse.requestTimeoutMs,
  fetchImpl = fetch,
}) {
  if (!jobId) {
    throw new LlamaParseError("LLAMA_BAD_REQUEST", "missing job id");
  }
  const data = await requestJson(
    `/api/v2/parse/${encodeURIComponent(jobId)}?expand=markdown,usage`,
    { timeoutMs, fetchImpl },
  );
  const job = data?.job ?? data;
  const status = parseStatus(job);
  const rawPages = Array.isArray(data?.markdown?.pages) ? data.markdown.pages : [];
  const pages = rawPages.map((page, index) => ({
    pageNumber: Number.isFinite(page?.page_number)
      ? page.page_number
      : Number.isFinite(page?.page)
        ? page.page
        : index + 1,
    success: page?.success !== false,
    markdown: typeof page?.markdown === "string" ? page.markdown : "",
    error: page?.error ?? null,
  }));

  return {
    jobId,
    status,
    credits: creditsOf(job),
    errorMessage: job?.error_message ?? null,
    pages,
    pagesFailed: pages.filter((page) => !page.success).length,
  };
}
